#!/usr/bin/env node
/**
 * Regenerates the DiffSeek live-E2E fixture tree.
 *
 * Default output: .cache/diffseek-test-data/ (gitignored)
 * Override with DIFFSEEK_FIXTURE_ROOT=/path/to/sha-tm/diffseek-test-data
 *
 * Layout goals (see README.md for DiffSeek coverage notes):
 * - Branchy nested folders under 7 Mortal Kombat–named top-level arenas
 * - Exactly 5 animal `group=` values via root `.gitattributes`
 * - CODEOWNERS on each top-level arena (7 usernames)
 * - Every second folder and every second file marked generated, with
 *   `-linguist-generated` overrides where folder/file parity disagree
 * - ts / tsx / css / json files (tsx shares TypeScript with ts for aggregate labels)
 * - A few extensionless + binary paths for edge contracts
 */

import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const root = resolve(
  process.env.DIFFSEEK_FIXTURE_ROOT ?? join(repoRoot, '.cache/diffseek-test-data'),
);
const seed = Number(process.env.DIFFSEEK_FIXTURE_SEED ?? 185108);

/** @type {readonly string[]} */
const OWNERS = freezeSample(
  [
    'Scorpion',
    'SubZero',
    'Raiden',
    'LiuKang',
    'Kitana',
    'Jax',
    'ShangTsung',
    'JohnnyCage',
    'SonyaBlade',
    'Mileena',
    'KungLao',
    'Baraka',
    'Reptile',
    'Smoke',
  ],
  7,
  seed,
);

/** @type {readonly string[]} */
const GROUPS = ['Fox', 'Otter', 'Badger', 'Lynx', 'Crane'];

/** @type {readonly string[]} */
const EXTENSIONS = ['ts', 'tsx', 'css', 'json'];

const DEPTH = 3;
const BRANCH_FACTOR = 2;
const FILES_PER_LEAF = 3;

/**
 * @param {readonly string[]} pool
 * @param {number} count
 * @param {number} startSeed
 */
function freezeSample(pool, count, startSeed) {
  const rng = mulberry32(startSeed);
  const copy = [...pool];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, count);
}

/** @param {number} a */
function mulberry32(a) {
  return () => {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * @param {string} owner
 * @param {number} depth
 * @param {string[]} trail
 * @param {{ folders: string[]; files: string[] }} out
 */
function walkArena(owner, depth, trail, out) {
  const folderPath = trail.join('/');
  out.folders.push(folderPath);

  if (depth >= DEPTH) {
    for (let i = 0; i < FILES_PER_LEAF; i += 1) {
      const extension = EXTENSIONS[(out.files.length + i) % EXTENSIONS.length];
      out.files.push(`${folderPath}/shard-${i}.${extension}`);
    }
    return;
  }

  for (let branch = 0; branch < BRANCH_FACTOR; branch += 1) {
    walkArena(owner, depth + 1, [...trail, `nest-${depth}-${branch}`], out);
  }
}

function planTree() {
  /** @type {{ folders: string[]; files: string[] }} */
  const out = { folders: [], files: [] };

  for (const owner of OWNERS) {
    const arena = owner.toLowerCase();
    walkArena(owner, 0, [arena], out);
  }

  // Ungrouped / unowned corner cases for DiffSeek fallbacks.
  out.folders.push('neutral', 'neutral/loose');
  out.files.push(
    'neutral/loose/readme',
    'neutral/loose/notes',
    'neutral/loose/asset.bin',
    'neutral/loose/orphan.ts',
  );

  return out;
}

/**
 * @param {string[]} folders
 * @param {string[]} files
 */
function buildGitAttributes(folders, files) {
  const lines = [
    '# Generated by scripts/diffseek-test-data/generate-fixture-tree.mjs — do not hand-edit.',
    '# Last matching assignment wins per attribute (DiffSeek contract).',
    '',
    '# Languages: explicit overrides so ts+tsx aggregate as TypeScript.',
    '*.ts linguist-language=TypeScript',
    '*.tsx linguist-language=TypeScript',
    '*.css linguist-language=CSS',
    '*.json linguist-language=JSON',
    '',
    '# Animal groups — five values across seven MK arenas (shared groups).',
  ];

  OWNERS.forEach((owner, index) => {
    const arena = owner.toLowerCase();
    const group = GROUPS[index % GROUPS.length];
    lines.push(`${arena}/** group=${group}`);
  });

  lines.push(
    '',
    '# Folder-level generated markers (every second folder in creation order).',
  );
  folders.forEach((folder, index) => {
    if (index % 2 === 1) {
      lines.push(`${folder}/** linguist-generated`);
    }
  });

  lines.push(
    '',
    '# File-level generated parity + overrides when folder/file disagree.',
  );
  const generatedFolders = new Set(
    folders.filter((_, index) => index % 2 === 1),
  );

  files.forEach((file, index) => {
    const parentGenerated = [...generatedFolders].some(
      (folder) => file === folder || file.startsWith(`${folder}/`),
    );
    const fileGenerated = index % 2 === 1;
    if (fileGenerated && !parentGenerated) {
      lines.push(`${file} linguist-generated`);
    } else if (!fileGenerated && parentGenerated) {
      lines.push(`${file} -linguist-generated`);
    } else if (fileGenerated && parentGenerated) {
      // Explicit keep for readability in reviews.
      lines.push(`${file} linguist-generated`);
    }
  });

  lines.push('');
  return `${lines.join('\n')}\n`;
}

/**
 * @param {string[]} files
 */
function buildCodeowners(files) {
  const lines = [
    '# Generated by scripts/diffseek-test-data/generate-fixture-tree.mjs — do not hand-edit.',
    '# Top-level MK arenas only; neutral/** stays Unmapped for DiffSeek.',
    '',
  ];
  for (const owner of OWNERS) {
    lines.push(`/${owner.toLowerCase()}/ @${owner}`);
  }
  lines.push('');
  // Touch files list so callers can assert coverage stats without scanning disk.
  lines.push(`# planned-files: ${files.length}`);
  lines.push('');
  return `${lines.join('\n')}\n`;
}

/**
 * @param {string} filePath
 * @param {number} index
 */
function fileContents(filePath, index) {
  if (filePath.endsWith('.bin')) {
    return Buffer.from([0x00, 0x01, 0x02, 0x44, 0x53, index & 0xff]);
  }
  if (!filePath.includes('.')) {
    return `extensionless fixture ${filePath} #${index}\n`;
  }
  if (filePath.endsWith('.json')) {
    return `${JSON.stringify({ path: filePath, index, seed }, null, 2)}\n`;
  }
  if (filePath.endsWith('.css')) {
    return `/* ${filePath} */\n.fixture-${index} { color: #334; }\n`;
  }
  if (filePath.endsWith('.tsx')) {
    return `export const Fixture${index} = () => <span>{${JSON.stringify(filePath)}}</span>;\n`;
  }
  return `export const fixture${index} = ${JSON.stringify(filePath)};\n`;
}

async function writeTree() {
  const { folders, files } = planTree();

  // Wipe previous generated arenas + metadata; keep scripts/ and docs.
  for (const owner of OWNERS) {
    await rm(join(root, owner.toLowerCase()), { recursive: true, force: true });
  }
  await rm(join(root, 'neutral'), { recursive: true, force: true });

  for (const folder of folders) {
    await mkdir(join(root, folder), { recursive: true });
  }

  await Promise.all(
    files.map(async (file, index) => {
      const absolute = join(root, file);
      await mkdir(dirname(absolute), { recursive: true });
      await writeFile(absolute, fileContents(file, index));
    }),
  );

  await writeFile(join(root, '.gitattributes'), buildGitAttributes(folders, files));
  await writeFile(join(root, 'CODEOWNERS'), buildCodeowners(files));

  const generatedFolderCount = folders.filter((_, i) => i % 2 === 1).length;
  const generatedFileCount = files.filter((_, i) => i % 2 === 1).length;

  console.log(
    JSON.stringify(
      {
        root: relative(process.cwd(), root) || '.',
        seed,
        owners: OWNERS.map((owner) => `@${owner}`),
        groups: GROUPS,
        folders: folders.length,
        files: files.length,
        generatedFolders: generatedFolderCount,
        generatedFiles: generatedFileCount,
      },
      null,
      2,
    ),
  );
}

await writeTree();
